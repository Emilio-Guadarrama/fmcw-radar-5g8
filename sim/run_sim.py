"""Regenerate the Gate 0 simulation plots and summary in sim/out/.

Run from the repository root:  python sim/run_sim.py
Simulation only. Amplitudes and noise are assumptions, not a link budget.
"""

from dataclasses import replace
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import fmcw
import matplotlib.pyplot as plt
import numpy as np

OUT = Path(__file__).parent / "out"
SEED = 0
TARGET_M = 30.0
AMPLITUDE_V = 0.1  # assumption, peak volts at the ADC
NOISE_RMS_V = AMPLITUDE_V / np.sqrt(2)  # assumption: 0 dB per-sample SNR


def save(fig, name):
    fig.tight_layout()
    fig.savefig(OUT / name, dpi=130)
    plt.close(fig)


def plot_chirp_and_beat(cfg):
    t = cfg.sample_times()
    clean = fmcw.beat_signal(cfg, [(TARGET_M, AMPLITUDE_V)])
    noisy = fmcw.capture(
        cfg, [(TARGET_M, AMPLITUDE_V)], NOISE_RMS_V, np.random.default_rng(SEED)
    )
    fig, (a, b) = plt.subplots(2, 1, figsize=(9, 6))
    a.plot(t * 1e3, fmcw.chirp_frequency_hz(cfg, t) / 1e9)
    a.set(xlabel="time (ms)", ylabel="TX frequency (GHz)", title="Ideal chirp")
    b.plot(t * 1e3, noisy, label="0 dB SNR, quantized (assumption)")
    b.plot(t * 1e3, clean, label="noiseless")
    b.set(xlabel="time (ms)", ylabel="V", title="Beat signal, 30 m (simulated)")
    b.legend()
    save(fig, "chirp_and_beat.png")


def plot_range_fft(cfg):
    x = fmcw.capture(
        cfg, [(TARGET_M, AMPLITUDE_V)], NOISE_RMS_V, np.random.default_rng(SEED)
    )
    fig, ax = plt.subplots(figsize=(9, 4))
    for window in ("rect", "hann"):
        r, a = fmcw.range_fft(cfg, x, window, 16 * x.size)
        ax.plot(r, 20 * np.log10(a + 1e-12), label=window)
    ax.axvline(TARGET_M, color="k", ls=":", lw=1)
    ax.set(xlabel="range (m)", ylabel="dB re 1 V peak", ylim=(-70, -10))
    ax.set_title("Range FFT, 30 m target, 0 dB per-sample SNR (simulated)")
    ax.legend()
    save(fig, "range_fft_30m.png")


def resolution_table(cfg, window):
    """Fraction of 72 relative phases that resolve, for each separation."""
    separations = np.round(np.arange(0.5, 3.51, 0.1), 2)
    phases = np.linspace(0, 2 * np.pi, 72, endpoint=False)
    fraction = np.array(
        [
            np.mean(
                [fmcw.two_targets_resolved(cfg, 20.0, s, window, p) for p in phases]
            )
            for s in separations
        ]
    )
    failing = np.flatnonzero(fraction < 1)
    always = separations[failing[-1] + 1] if failing.size else separations[0]
    return separations, fraction, always


def worst_range_error_m(cfg):
    ranges = np.arange(3, 45.001, 0.05)
    return max(
        abs(fmcw.estimate_range_m(cfg, fmcw.capture(cfg, [(r, 0.8)])) - r)
        for r in ranges
    )


def main():
    OUT.mkdir(exist_ok=True)
    base = fmcw.RadarConfig()  # radiated design case, 115 MHz
    plot_chirp_and_beat(base)
    plot_range_fft(base)

    lines = [
        "# Gate 0 simulation summary (generated by sim/run_sim.py)",
        "",
        "Simulation only: ideal chirp, noiseless for the two columns of results.",
        "Two-target figure: equal echoes near 20 m, 72 relative phases, 3 dB dip,",
        "peaks within c/(8B) of truth (assumed criterion, separations in 0.1 m steps).",
        "Range error: single target, 3-45 m in 0.05 m steps, Hann, 16x padding,",
        "12-bit ADC, 0.8 V peak on a +/-1 V input.",
        "",
        (
            "| B (MHz) | c/(2B) (m) | f_b at 30 m (Hz) | resolved at all phases, rect (m)"
            " | same, Hann (m) | worst range error (mm) |"
        ),
        "|---|---|---|---|---|---|",
    ]
    fig, ax = plt.subplots(figsize=(9, 4))
    for cfg in (
        fmcw.CONDUCTED_150MHZ,
        replace(base, f_start_hz=5.725e9, bandwidth_hz=125e6),
        base,
    ):
        bandwidth = cfg.bandwidth_hz
        always = {}
        for window, style in (("rect", "--"), ("hann", "-")):
            sep, fraction, always[window] = resolution_table(cfg, window)
            ax.plot(sep, fraction, style, label=f"{bandwidth / 1e6:.0f} MHz {window}")
        lines.append(
            f"| {bandwidth / 1e6:.0f} | {cfg.range_resolution_m:.3f} "
            f"| {cfg.beat_frequency_hz(TARGET_M):.0f} | {always['rect']:.1f} "
            f"| {always['hann']:.1f} | {worst_range_error_m(cfg) * 1e3:.1f} |"
        )
    ax.set(xlabel="target separation (m)", ylabel="fraction of phases resolved")
    ax.set_title("Two equal targets (simulated, noiseless)")
    ax.legend()
    save(fig, "two_target_resolution.png")

    summary = "\n".join(lines) + "\n"
    (OUT / "summary.md").write_text(summary, encoding="utf-8")
    print(summary)


if __name__ == "__main__":
    main()
